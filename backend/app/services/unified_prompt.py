def resolve_score(label_l2: str, action_type: str, raw_score) -> tuple[int, str]:
    """축 A 라벨 구간으로 점수를 보정하고, 삭제대상이면 '높음'까지 올린다.

    라벨별 구간은 라벨링 데이터 10,056건으로 캘리브레이션된 값이라 그대로 쓰되,
    축 B가 삭제대상으로 본 글이 '위험 낮음'으로 표시되는 모순만 막는다.
    """
    lo, hi = LABEL_SCORE_RANGES.get(label_l2, (0, 33))
    try:
        score = int(raw_score)
    except (TypeError, ValueError):
        score = lo
    score = max(lo, min(hi, score))
    if action_type == "삭제대상":
        score = max(score, DELETE_SCORE_FLOOR)
    level = "낮음" if score <= 33 else ("중간" if score <= 66 else "높음")
    return score, level


def parse_unified(data: dict) -> dict:
    """Gemini JSON 응답을 두 축 모두 검증·보정해 저장용 dict로 변환."""
    label = str(data.get("label_l2", "")).strip()
    if label not in ALL_LABELS:
        label = "단순내용"

    subject = str(data.get("subject", "")).strip()
    if subject not in SUBJECTS:
        subject = "기타"

    category = data.get("category")
    if category not in VALID_CATEGORIES:
        category = "해당없음"
    # 정책비판만 AI의 action_type을 존중, 나머지는 결정적 매핑
    if category in CATEGORY_TO_ACTION:
        action_type = CATEGORY_TO_ACTION[category]
    else:
        action_type = data.get("action_type")
        if action_type not in VALID_ACTIONS:
            action_type = "비대상"

    intent = data.get("intent_type")
    if intent not in VALID_INTENTS:
        intent = "불명확"
    content = data.get("content_type")
    if content not in VALID_CONTENTS:
        content = "문제없음"

    score, level = resolve_score(label, action_type, data.get("false_score"))

    names = data.get("department_names")
    if isinstance(names, str):
        names = [names]
    elif not isinstance(names, list):
        names = []
    names = [str(n).strip() for n in names if str(n).strip()][:2]

    return {
        "label_l1":         "조장정보" if label in PROMOTION_LABELS else "단순병역정보",
        "label_l2":         label,
        "subject":          subject,
        "category":         category,
        "action_type":      action_type,
        "intent_type":      intent,
        "content_type":     content,
        "false_score":      score,
        "false_level":      level,
        "false_reason":     str(data.get("false_reason", data.get("reason", "")))[:100],
        "department_names": names,
    }
